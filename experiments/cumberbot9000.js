function analyse(text, config) {
  if (!config) return null;
  const parts = text.trim().split(/\s+/);
  if (parts.length !== 2) return null;
  const score = (jaroWinkler(parts[0], config.reference[0]) + jaroWinkler(parts[1], config.reference[1])) / 2;
  return { rawScore: score, percent: Math.round(score * 100), category: score >= config.thresholds[1] ? 'close' : score >= config.thresholds[0] ? 'mid' : 'far' };
}
// Full-population percentile boundaries (51,230 equally likely combinations).
// Exact unrounded comparisons; boundary ties are included.
const PERCENTILE_LIMITS = {
  bottom5: 0.45941558441558444,
  bottom10: 0.4750180375180375,
  top10: 0.6135882635882635,
  top5: 0.6450757575757576
};
function percentileFlag(score) {
  const x = score.rawScore;
  if (x >= PERCENTILE_LIMITS.top5 - 1e-12) return 'TOP 5%';
  if (x >= PERCENTILE_LIMITS.top10 - 1e-12) return 'TOP 10%';
  if (x <= PERCENTILE_LIMITS.bottom5 + 1e-12) return 'BOTTOM 5%';
  if (x <= PERCENTILE_LIMITS.bottom10 + 1e-12) return 'BOTTOM 10%';
  return null;
}
